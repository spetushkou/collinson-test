// Keeps the prettier and oxlint ignore lists in step with .gitignore.
//
// .gitignore is the source of truth; each tool's list is .gitignore plus that tool's
// extras. oxlint needs its own copy because it honours .gitignore only when it walks
// a directory - given explicit file paths, as lint-staged passes them, it lints a
// gitignored file anyway.
//
//   node scripts/sync-ignores.mjs           rewrite .prettierignore and .oxlintrc.json
//   node scripts/sync-ignores.mjs --check   exit 1 if either one has drifted
import { readFileSync, writeFileSync } from 'node:fs';

const EXTRAS = {
  prettier: [
    'pnpm-lock.yaml',
    'schema.gql',
    '.oxlintrc.json',
    'drizzle/',
    'test/fixtures/',
  ],
  oxlint: [],
};

const HEADER = [
  '# GENERATED by scripts/sync-ignores.mjs from .gitignore - do not edit by hand.',
  '# Change .gitignore (or the extras in the script) and run `pnpm ignore:sync`.',
];

const gitignore = readFileSync('.gitignore', 'utf8')
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#'));

const prettierignore =
  [...HEADER, '', ...gitignore, '', '# prettier only', ...EXTRAS.prettier].join(
    '\n',
  ) + '\n';

const oxlintrc = JSON.parse(readFileSync('.oxlintrc.json', 'utf8'));
oxlintrc.ignorePatterns = [...gitignore, ...EXTRAS.oxlint];
const oxlintJson = JSON.stringify(oxlintrc, null, 2) + '\n';

const targets = [
  ['.prettierignore', prettierignore],
  ['.oxlintrc.json', oxlintJson],
];

if (process.argv.includes('--check')) {
  const drifted = targets.filter(
    ([file, wanted]) => readFileSync(file, 'utf8') !== wanted,
  );
  for (const [file] of drifted) {
    console.error(
      `${file} is out of sync with .gitignore - run pnpm ignore:sync`,
    );
  }
  process.exit(drifted.length ? 1 : 0);
}

for (const [file, content] of targets) writeFileSync(file, content);
console.log('.prettierignore and .oxlintrc.json synced from .gitignore');
